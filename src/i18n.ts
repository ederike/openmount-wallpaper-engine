export type MsgKey = keyof typeof zh;
const catalogs: Record<Locale, Record<MsgKey, string>> = { zh, en };

export function translate(locale: Locale, key: MsgKey): string {
  return catalogs[locale][key] ?? catalogs.en[key] ?? key;
}

export function actionLabel(locale: Locale, action: string): string {
  const key = `action_${action}` as MsgKey;
  return catalogs[locale][key] ?? catalogs.en[key] ?? action;
}

export function useT() {
  const locale = useAppStore((s) => s.locale);
  const t = (key: MsgKey) => translate(locale, key);
  t.locale = locale;
  t.action = (action: string) => actionLabel(locale, action);
  return t as ((key: MsgKey) => string) & { locale: Locale; action: (action: string) => string };
}
